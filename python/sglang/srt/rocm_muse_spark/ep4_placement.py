TABLES = {"fit": LAYER_MAP, "1": LAYER_MAP, "vllm": VLLM_FOLDED, "vllm-e17": VLLM_E17_FOLDED}


def selected() -> str | None:
    name = os.environ.get("SGLANG_MUSE_EP4_PLACEMENT", "0")
    if name in ("", "0"):
        return None
    if name not in TABLES:
        raise ValueError(f"SGLANG_MUSE_EP4_PLACEMENT={name!r}: expected one of 0, {', '.join(TABLES)}")
    return name


def layer_slots(ep_size: int, num_experts: int) -> dict[int, tuple[torch.Tensor, torch.Tensor]]:
    """layer -> (physical slot of each logical expert, logical expert of each physical slot), int64 on CPU.

    Empty when no table is selected, or the table was not built for this EP size and expert count."""
    name = selected()
    if name is None or ep_size != EP_SIZE or num_experts != NUM_EXPERTS:
        return {}
    out = {}
    local = num_experts // ep_size
    for layer, row in TABLES[name].items():
        ranks = torch.tensor([int(c) for c in row], dtype=torch.int64)
        assert ranks.numel() == num_experts, f"layer {layer}: {ranks.numel()} entries"
        assert torch.bincount(ranks, minlength=ep_size).tolist() == [local] * ep_size, f"layer {layer} unbalanced"
        # rank-major, ascending logical id within a rank
        logical = torch.argsort(ranks * num_experts + torch.arange(num_experts))
        slot = torch.empty_like(logical)
        slot[logical] = torch.arange(num_experts)
        out[layer] = (slot, logical)
    return out
